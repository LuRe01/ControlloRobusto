function u0Now = trimAtDelta( ...
    delta,p0,alpha0,beta0)

    m = ...
        p0.m * ...
        (1+0.10*delta(4));

    ep = ...
        p0.epsilon_p * ...
        (1+0.30*delta(6));

    ey = ...
        p0.epsilon_y * ...
        (1+0.30*delta(7));

    E = [
        cos(beta0),        ep*sin(beta0);
        ey*sin(alpha0),    cos(alpha0)
        ];

    u0Now = ...
        E \ [
        m*p0.g*sin(alpha0);
        0
        ];

end

function [p2y,y2p] = staticMisalignment( ...
    delta,PuncExt,Dy_inv,Du,Ddec)

    P = ...
        evaluatePlant( ...
            PuncExt, ...
            delta);

    G = ...
        P([1 3],[1 2]);

    M = ...
        dcgain( ...
            Dy_inv * ...
            G * ...
            Du) * ...
        Ddec;

    p2y = ...
        100 * ...
        abs(M(2,1)) / ...
        max(norm(M(:,1),2),eps);

    y2p = ...
        100 * ...
        abs(M(1,2)) / ...
        max(norm(M(:,2),2),eps);

end

function Pdet = evaluatePlant( ...
    PuncExt,delta)

    names = {
        'J_alpha'
        'J_y'
        'J_z'
        'm'
        'l'
        'epsilon_p'
        'epsilon_y'
        };

    U = ...
        PuncExt.Uncertainty;

    Pwork = ...
        PuncExt;

    for i = 1:numel(names)

        blk = ...
            U.(names{i});

        d = ...
            max( ...
                -1, ...
                min( ...
                    1, ...
                    delta(i)));

        if d >= 0

            value = ...
                blk.NominalValue + ...
                d * ...
                ( ...
                    blk.Range(2) - ...
                    blk.NominalValue);

        else

            value = ...
                blk.NominalValue + ...
                (-d) * ...
                ( ...
                    blk.Range(1) - ...
                    blk.NominalValue);

        end

        Pwork = ...
            usubs( ...
                Pwork, ...
                names{i}, ...
                value);

    end

    Pdet = ...
        ss(Pwork);

end

function logs = getLogs(out)

    try

        logs = out.logsout;

    catch

        logs = out.get('logsout');

    end

    if isempty(logs)
        error('logsout non disponibile.');
    end

end

function ts = getTs(logs,name)

    el = ...
        logs.get(name);

    if isempty(el)

        error( ...
            'Segnale %s non trovato in logsout.', ...
            name);

    end

    ts = ...
        el.Values;

    ts.Data = ...
        squeeze(ts.Data);

end

