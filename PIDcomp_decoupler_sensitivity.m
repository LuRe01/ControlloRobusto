        'act',actRun);

    in = in.setVariable( ...
        'sensor',sensorRun);

    in = in.setModelParameter( ...
        'StopTime',num2str(cfg.stopTime));

    in = in.setModelParameter( ...
        'UnderSpecifiedDimensionMsg','none');

    if k == 1
        label = 'Nominale';
    else
        label = sprintf('Sample %d',k-1);
    end

    fprintf('[%02d/%02d] %s\n', ...
        k,nCases,label);

    try

        out = sim(in);

        outputs{k} = out;
        success(k) = true;

        logs = getLogs(out);

        a = getTs( ...
            logs,'alpha_Robust');

        b = getTs( ...
            logs,'beta_Robust');

        aRef = getTs( ...
            logs,'alpha_ref');

        bRef = getTs( ...
            logs,'beta_ref');

        u1 = getTs( ...
            logs,'deltaF1_cmd_Robust');

        u2 = getTs( ...
            logs,'deltaF2_cmd_Robust');

        %% Riferimenti sulla griglia delle uscite
        aRefI = interp1( ...
            aRef.Time, ...
            aRef.Data, ...
            a.Time, ...
            'previous', ...
            'extrap');

        bRefI = interp1( ...
            bRef.Time, ...
            bRef.Data, ...
            b.Time, ...
            'previous', ...
            'extrap');

        %% ---------------------------------------------------------------
        % PITCH -> YAW
        % ---------------------------------------------------------------
        pitchWindow = ...
            b.Time >= cfg.alphaStepTime & ...
            b.Time <  cfg.betaStepTime;

        betaCross = ...
            b.Data - bRefI;

        pitchToYawPeakDeg(k) = ...
            rad2deg( ...
                max( ...
                    abs( ...
                        betaCross(pitchWindow))));

        pitchToYawPeakPct(k) = ...
            100 * ...
            pitchToYawPeakDeg(k) / ...
            abs(rad2deg(cfg.alphaStep));

        %% ---------------------------------------------------------------
        % YAW -> PITCH
        % ---------------------------------------------------------------
        eAlpha = ...
            aRefI - a.Data;

        preYaw = ...
            a.Time >= ...
                cfg.betaStepTime-cfg.preYawBaseline & ...
            a.Time < ...
                cfg.betaStepTime-0.05;

        if any(preYaw)

            baseEA = mean( ...
                eAlpha(preYaw));

        else

            baseEA = 0;

        end

        yawWindow = ...
            a.Time >= cfg.betaStepTime;

        alphaCross = ...
            eAlpha - baseEA;

        yawToPitchPeakDeg(k) = ...
            rad2deg( ...
                max( ...
                    abs( ...
                        alphaCross(yawWindow))));

        yawToPitchPeakPct(k) = ...
            100 * ...
            yawToPitchPeakDeg(k) / ...
            abs(rad2deg(cfg.betaStep));

        %% ---------------------------------------------------------------
        % Saturazione
        % ---------------------------------------------------------------
        maxAbsU1Cmd(k) = ...
            max(abs(u1.Data));

        maxAbsU2Cmd(k) = ...
            max(abs(u2.Data));

        saturationHit(k) = ...
            any( ...
                u1.Data < ...
                    actRun.deltaF1_min-1e-9) || ...
            any( ...
                u1.Data > ...
                    actRun.deltaF1_max+1e-9) || ...
            any( ...
                u2.Data < ...
                    actRun.deltaF2_min-1e-9) || ...
            any( ...
                u2.Data > ...
                    actRun.deltaF2_max+1e-9);

    catch ME

        warning( ...
            '%s fallito: %s', ...
            label, ...
            ME.message);

    end
end

