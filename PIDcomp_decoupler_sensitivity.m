if ~isfile([cfg.model '.slx']) && isfile('helicopter_2DOF(2).slx')
    cfg.model = 'helicopter_2DOF(2)';
end

cfg.nSamples = 15;             % 15 plant incerti + 1 nominale di confronto
cfg.seed = 260902;
cfg.stopTime = 15;

cfg.alphaStepTime = 2;
cfg.betaStepTime  = 8;

cfg.alphaStep = deg2rad(3);
cfg.betaStep  = deg2rad(-5);

cfg.preYawBaseline = 0.75;

% TRUE = consigliato per la figura principale:
% ogni plant parte dal proprio equilibrio.
cfg.useMatchedTrim = true;

cfg.showFigures = false;
cfg.pngResolution = 300;

cfg.outputDir = fullfile( ...
    projectRoot, ...
    'decoupler_sensitivity_result', ...
    'decoupler_sensitivity_PIDcomp');

