    Bobs  = [B Ke];
    Cobs  = eye(size(A));
    Dobs  = zeros(size(A,1),size(B,2)+size(Cmeas,1));
    xhat0 = zeros(size(A,1),1);
end

assert(exist('Ddec_scaled','var')==1,'Ddec_scaled mancante.');
assert(exist('P_uncertain_ext','var')==1,'P_uncertain_ext mancante.');

%% 1) Configurazione
