%% 2) Test sequenziale per le due direzioni di coupling
%
% 2...8 s:
% alpha cambia, beta_ref resta costante.
% beta-beta_ref = coupling pitch -> yaw.
%
% da 8 s:
% beta cambia, alpha_ref resta costante.
% nuova escursione di e_alpha = coupling yaw -> pitch.

refRun = ref;

refRun.alpha.initial = alpha0;
refRun.alpha.final   = alpha0 + cfg.alphaStep;
refRun.alpha.time    = cfg.alphaStepTime;

refRun.beta.initial = beta0;
refRun.beta.final   = beta0 + cfg.betaStep;
refRun.beta.time    = cfg.betaStepTime;

% Nessun disturbo aerodinamico.
aeroRun = aero;
aeroRun.enable = 0;
aeroRun.alpha.amplitude = 0;
aeroRun.beta.amplitude  = 0;

% Attuatori nominali e rumori disattivati.
actRun = act;
actRun.noiseEnable = 0;

sensorRun = sensor;
sensorRun.noiseEnable = 0;

%% 3) Campioni parametrici del plant non lineare
%
% Ordine:
% [J_alpha, J_y, J_z, m, l, epsilon_p, epsilon_y]

rng(cfg.seed,'twister');

deltaSamples = -1 + 2*rand(7,cfg.nSamples);

% Sample severo gia' usato nel progetto.
